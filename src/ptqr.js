/* Writes parts/data23.js: PT_QR, the QR codes that open home care advice on a patient's own phone (12 Nov 2026).
   One code per advice and language, each opening APP_URL + '#pt-<id>' (or '#pt-<id>-ms' for Bahasa Melayu) on the public web
   app. Only advice written for the patient: the two CPG leaflets (English and Bahasa Melayu) and the advice tabs that are read
   aloud (English). Run `node ptqr.js` after changing the list or APP_URL; test.js reads every code back with qr.js.
   Do not edit data23.js by hand. */
'use strict';
const fs = require('fs'), path = require('path');
const {encode, decode, path: qrPath} = require('./qr.js');

const engine = fs.readFileSync(path.join(__dirname, 'parts', 'engine.js'), 'utf8');
const APP_URL = (engine.match(/const APP_URL = '([^']+)'/) || [])[1];
if (!APP_URL) throw new Error('APP_URL not found in engine.js');

/* id: languages. Leaflets in both languages; the read-aloud advice tabs in English (as recorded) */
const LIST = {
  'dengue-cpg': ['en', 'ms'], 'cancer-pain-cpg': ['en', 'ms'],
  'mild-tbi': ['en'], 'asthma-zone': ['en'], 'gastroenteritis': ['en'], 'renal-colic': ['en'], 'abdominal-pain': ['en'], 'hypoglycaemia': ['en']
};

const out = {};
for (const [id, langs] of Object.entries(LIST)){
  out[id] = {};
  for (const lg of langs){
    const u = APP_URL + '#pt-' + id + (lg === 'ms' ? '-ms' : '');
    const qr = encode(u, 'M');
    const back = decode(qr.modules);
    if (back.text !== u || !back.eccOk) throw new Error('QR does not read back: ' + u + ' -> ' + back.text);
    out[id][lg] = {u, n: qr.modules.length, d: qrPath(qr)};
  }
}
const js = `/* Generated by src/ptqr.js on ${new Date().toISOString().slice(0, 10)}: do not edit by hand.
   PT_QR: the QR codes that open home care advice on a patient's own phone (the web app's #pt- pages).
   Each is {u: the address, n: modules a side, d: an SVG path, one unit a module}. */
const PT_QR = ${JSON.stringify(out)};
`;
fs.writeFileSync(path.join(__dirname, 'parts', 'data23.js'), js);
console.log('data23.js: ' + Object.values(out).reduce((s, o) => s + Object.keys(o).length, 0) + ' codes, ' + Math.round(js.length / 1024) + ' KB');
