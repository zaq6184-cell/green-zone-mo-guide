/* Builds parts/data17.js, the outlines of the nine abdominal regions on each frame of the 3D turntable (12 Nov 2026).
   Reads ../sources/abdo/abdo3d-regions.json (git-ignored; written by the Blender scene sources/abdo/abdo3d.blend, which
   renders ../app/abdo3d/f00.webp to f24.webp, front-lit/r1.webp to r9.webp and poster.webp) and keeps every other outline
   point, as SVG points strings. Usage: node abdo3d.js */
const fs = require('fs'), path = require('path');
const SRC = [path.join(__dirname, '..', 'sources', 'abdo', 'abdo3d-regions.json'), path.join(__dirname, '..', 'app', 'abdo3d', 'regions.json')].find(f => fs.existsSync(f));
if (!SRC) throw new Error('abdo3d-regions.json not found');
const j = JSON.parse(fs.readFileSync(SRC, 'utf8'));
if (!j.w || !j.h || !Array.isArray(j.frames) || j.frames.length !== 25) throw new Error('unexpected regions.json');
const frames = j.frames.map((f, i) => {
  if (f.i !== i) throw new Error('frame order');
  const regs = [];
  for (let r = 1; r <= 9; r++){
    const p = f.regions[String(r)]; if (!p || p.length < 8) throw new Error('frame ' + i + ' region ' + r);
    regs.push(p.filter((_, k) => k % 2 === 0).map(q => Math.round(q[0]) + ',' + Math.round(q[1])).join(' '));
  }
  return [f.yaw, regs];
});
const front = j.front != null ? j.front : 12;
if (frames[front][0] !== 0) throw new Error('front frame is not yaw 0');
const js = '/* ================= The 3D abdomen map: region outlines per turntable frame, generated by src/abdo3d.js (do not edit by hand) =================\n' +
  '   25 frames from yaw -36 to +36 degrees (3 degrees a step; positive turns toward the patient\'s left); frame ' + front + ' is the front view, where the\n' +
  '   patient\'s right is on the screen\'s left. Each frame: [yaw, [region 1 outline, ..., region 9 outline]] in 720 x 900 image pixels. */\n' +
  'const A3D = ' + JSON.stringify({w: j.w, h: j.h, front, frames}) + ';\n';
fs.writeFileSync(path.join(__dirname, 'parts', 'data17.js'), js);
console.log('frames:', frames.length, '| front:', front, '| data17.js bytes:', js.length, '| from', path.relative(path.join(__dirname, '..'), SRC));
