/* Builds the X-ray films of the guide from the traced outlines (12 Nov 2026).
   Reads every ../sources/xray/<key>.json (git-ignored: the working film <key>.jpg, its size, title, credit, the source of the
   names and each part's outline), writes ../app/xray/<key>.webp and parts/data15.js (the films and which step of the X-ray
   guide shows which). The wrist PA, the approved pilot, stays in parts/data14.js and is skipped here.
   Usage: node xfilms.js     (needs ffmpeg on the PATH) */
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const SRC = path.join(__dirname, '..', 'sources', 'xray'), OUT = path.join(__dirname, '..', 'app', 'xray');
/* Which step of xray-guide shows which films, in reading order */
const GROUPS = {
  cxd: ['chest-pa'], ankv: ['ankle-ap', 'ankle-mortise', 'ankle-lat'], ftv: ['foot-dp', 'foot-oblique', 'foot-lat'],
  knv: ['knee-ap', 'knee-lat'], wrl: ['wrist-lat'], hd: ['hand-pa', 'hand-oblique'], elr: ['elbow-ap', 'elbow-lat'],
  sh: ['shoulder-ap', 'shoulder-y'], hp2: ['pelvis-ap']
};
/* A long list of parts is grouped in the key under the film: [label, [part keys]]. A part in no group stays a pill of its own. */
const FINGERS = [['Little finger', ['d5', 'm5', 'p5']], ['Ring finger', ['d4', 'm4', 'p4']], ['Middle finger', ['d3', 'm3', 'p3']], ['Index finger', ['d2', 'm2', 'p2']]];
const KEYGROUPS = {
  'hand-pa': [...FINGERS, ['Thumb', ['d1', 'p1', 'sesamoid']], ['Metacarpals', ['mc1', 'mc2', 'mc3', 'mc4', 'mc5']], ['Carpal bones', ['scaphoid', 'lunate', 'triquetrum', 'pisiform', 'trapezium', 'trapezoid', 'capitate', 'hamate']]],
  'hand-oblique': [...FINGERS, ['Thumb', ['d1', 'p1']], ['Metacarpals', ['mc1', 'mc2', 'mc3', 'mc4', 'mc5']]]
};
/* Wording the source page asks for */
const TITLE = { 'knee-lat': 'Knee, lateral view: near normal (the film\'s page notes a minimal osteophyte at the upper rim of the patellofemoral joint)' };
fs.mkdirSync(OUT, { recursive: true });
const keys = [...new Set(Object.values(GROUPS).flat())];
const films = {};
for (const k of keys) {
  const j = JSON.parse(fs.readFileSync(path.join(SRC, k + '.json'), 'utf8'));
  if (!j.w || !j.h || !Array.isArray(j.parts) || !j.parts.length || !j.credit || !j.names) throw new Error(k + ': incomplete JSON');
  for (const p of j.parts) for (const q of p.p) if (q[0] < -1 || q[1] < -1 || q[0] > j.w + 1 || q[1] > j.h + 1) throw new Error(k + ': point outside the film in ' + p.k);
  execFileSync('ffmpeg', ['-v', 'error', '-y', '-i', path.join(SRC, j.film), '-c:v', 'libwebp', '-quality', '80', path.join(OUT, k + '.webp')]);
  if (KEYGROUPS[k]) { const have = new Set(j.parts.map(p => p.k)), seen = new Set(); for (const [l, ks] of KEYGROUPS[k]) for (const x of ks) { if (!have.has(x) || seen.has(x)) throw new Error(k + ': group ' + l + ' names ' + x); seen.add(x); } }
  films[k] = { ...(KEYGROUPS[k] ? { groups: KEYGROUPS[k] } : {}), t: TITLE[k] || j.t, w: j.w, h: j.h, alt: j.alt || j.t, credit: j.credit, names: j.names, parts: j.parts.map(p => ({ k: p.k, t: p.t, p: p.p.map(q => [Math.round(q[0]), Math.round(q[1])]) })) };
}
const js = '/* ================= X-ray films, generated by src/xfilms.js from the traced outlines (do not edit by hand) =================\n' +
  '   Each film is openly licensed (its credit says how) and was checked at full size for patient markings; the outlines are the\n' +
  '   guide\'s own tracing by eye. XGROUPS says which step of the X-ray guide shows which films. See data14.js for the rules. */\n' +
  'Object.assign(XFILMS, ' + JSON.stringify(films) + ');\n' +
  'const XGROUPS = ' + JSON.stringify(GROUPS) + ';\n' +
  "if (P['xray-guide']) Object.keys(XGROUPS).forEach(n => { const node = P['xray-guide'].nodes[n]; if (node && XGROUPS[n].every(k => XFILMS[k])) node.fig = 'xg-' + n; });\n";
fs.writeFileSync(path.join(__dirname, 'parts', 'data15.js'), js);
console.log('films:', keys.length, '| parts:', Object.values(films).reduce((a, f) => a + f.parts.length, 0), '| data15.js bytes:', js.length);
