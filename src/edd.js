// Builds parts/data21.js, the index of the ED dosing and dilution guide (Dosing and Dilution Guide of Injectable Drugs
// (Adult) Used in Emergency & Trauma Department HKL, 3rd edition, January 2026), from sources/starterpack/c/txt/c17-index.json
// (each drug's heading with its printed and PDF pages, from the guide's own pages). The doses are not copied: each drug opens
// the guide's own pages (app/sp/c17-p<N>.webp, built by `node memos.js starterpack`). "High alert" is a match against the
// hospital's List of High Alert Medications (2026), not the guide's own badge. Run: node edd.js
const fs = require('fs'), path = require('path');
const idx = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'sources', 'starterpack', 'c', 'txt', 'c17-index.json'), 'utf8'));
/* The 2026 list, by name as it would appear in a heading; strengths only where the list names one */
const HAM = [/adrenaline/i, /phenylephrine/i, /dopamine/i, /dobutamine/i, /esmolol/i, /labetalol/i, /ketamine/i, /thiopental/i, /propofol/i, /lignocaine|lidocaine/i, /amiodarone/i,
  /enoxaparin/i, /heparin/i, /warfarin/i, /fondaparinux/i, /rivaroxaban/i, /apixaban/i, /dabigatran/i, /alteplase/i, /streptokinase/i, /tenecteplase/i, /urokinase/i, /tirofiban/i,
  /dextrose 50/i, /^digoxin \d/i, /insulin/i, /bupivacaine/i, /ropivacaine/i, /dexmedetomidine/i, /midazolam/i, /atracurium/i, /rocuronium/i, /suxamethonium/i, /vecuronium/i,
  /fentanyl/i, /morphine/i, /oxycodone/i, /pethidine/i, /potassium chloride/i, /potassium dihydrogen/i, /magnesium sul/i, /calcium gluconate/i, /sodium bicarbonate 8\.4/i,
  /sodium chloride (20|3)%/i];
const items = idx.map(o => [o.n, o.name.replace(/\s+/g, ' ').trim(), o.q, o.qe, o.p, o.pe, HAM.some(r => r.test(o.name)) ? 1 : 0]);
if (items.length !== 116) throw new Error('expected 116 drugs');
/* A note on a drug's row, shown before its pages are opened: built only from what the drug's own page prints, checked on the page
   image (12 Nov 2026). The page itself is shown as printed. */
const NOTES = {
  64: 'Page 126 prints "60 mg midazolam + 600 mg fentanyl to 60 ml" for a patient needing a high dose; the same page prints 30 mg midazolam + 300 mcg fentanyl to 30 ml, and a final concentration of 10 mcg/ml of fentanyl. Still to confirm with the guide\'s authors.'
};
const out = `/* ================= GENERATED by src/edd.js: do not edit by hand =================
   The ED dosing and dilution guide: "Dosing and Dilution Guide of Injectable Drugs (Adult) Used in Emergency & Trauma
   Department, Hospital Kuala Lumpur", 3rd edition, January 2026 (Pharmacy Department HKL, reviewed by the department's
   emergency physicians). Krishna confirmed on 12 Nov 2026 that the department authorises it in the guide. 116 drugs as headed
   in the guide, each with its PDF pages (shown as app/sp/c17-p<N>.webp) and printed pages; nothing of the doses is retyped.
   The last field is 1 when the drug is on the hospital's List of High Alert Medications (2026). [n, name, pdf from, pdf to, printed from, printed to, high alert] */
const EDDG = {
  src:'Dosing and Dilution Guide of Injectable Drugs (Adult) Used in Emergency & Trauma Department, HKL, 3rd edition, January 2026',
  items:${JSON.stringify(items).replace(/\],\[/g, '],\n    [')},
  notes:${JSON.stringify(NOTES)}
};
`;
fs.writeFileSync(path.join(__dirname, 'parts', 'data21.js'), out);
console.log('data21.js: ' + items.length + ' drugs, ' + items.filter(i => i[6]).length + ' on the high alert list');
