// Builds the MOH Antidotes Quick Guide (Adult Dose), First Edition, January 2022, for the page #antidotes (21 Nov 2026):
//   app/data/antidotes.json  every entry as printed (its headings in their printed order, text unmodified), loaded on first use
//   parts/data30.js          AXIDX: each entry's name, what it is for and a generic name, for search and the drug finder card
// from the transcription read from its page images, sources/telegram/edhkl-announcements/work/reads/f279.json (git-ignored).
// The guide permits reproduction "provided that such reproduction be given due acknowledgement and shall not modify the text"
// (its page 2). Each entry's reference list is left out (it stays in the printed guide); nothing else is changed.
// Run: node antidotes.js
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'sources', 'telegram', 'edhkl-announcements', 'work', 'reads', 'f279.json');
const d = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const M = d.meta;
const doubts = Array.isArray(M.rows_with_dose_or_storage_doubts) ? M.rows_with_dose_or_storage_doubts : [];
const doubtOf = n => { const x = doubts.find(s => s.startsWith(n)); return x ? x.slice(n.length).trim().replace(/^\(|\)$/g, '') : null; };
/* A plain name for search and the drug finder: the words before the strength or form, title case */
const FORM = /^(\d|\(|INJECTION|TABLET|CAPSULE|GRANULES|SOLUTION|FOR$|ORAL|\[)/i;
const generic = n => { const w = []; for (const t of n.replace(/[₁]/g, '1').split(/\s+/)){ if (FORM.test(t) || /\d/.test(t)) break; w.push(t); } return w.join(' ').toLowerCase().replace(/(^|[\s/-])([a-z])/g, (m, a, b) => a + b.toUpperCase()); };
const rows = d.rows.map(r => ({
  n:r.antidote, f:r.for, p:r.printed_page,
  h:Object.entries(r.fields).filter(([k]) => !/^references?$/i.test(k)),
  q:doubtOf(r.antidote)
}));
if (rows.length !== 38) throw new Error('expected 38 entries, got ' + rows.length);
rows.forEach(r => { if (!r.h.some(([k]) => /^dosage/i.test(k))) console.log('note: no dosage heading in', r.n); });
const out = {meta:{t:M.title, ed:M.edition, date:M.date, issuer:'Pharmaceutical Services Programme, Ministry of Health Malaysia', code:M.publication_code, isbn:M.isbn,
  repro:M.reproduction, disclaimer:M.disclaimer}, rows};
fs.mkdirSync(path.join(ROOT, 'app', 'data'), {recursive:true});
fs.writeFileSync(path.join(ROOT, 'app', 'data', 'antidotes.json'), JSON.stringify(out));
const idx = rows.map((r, i) => [i, r.n, r.f, generic(r.n).replace(/^Vitamin$/, 'Vitamin K'), r.q ? 1 : 0]);
fs.writeFileSync(path.join(__dirname, 'parts', 'data30.js'),
  '/* Generated by src/antidotes.js from the checked transcription of the MOH Antidotes Quick Guide (Adult Dose), First Edition,\n' +
  '   January 2022: do not edit by hand. AXIDX: [index, entry name as printed, what it is for as printed, a plain name for search,\n' +
  '   1 where a dose or storage line is under Still to confirm]. The entries themselves are in app/data/antidotes.json. */\n' +
  'const AXIDX = ' + JSON.stringify(idx) + ';\n');
console.log('antidotes:', rows.length, 'entries,', fs.statSync(path.join(ROOT, 'app', 'data', 'antidotes.json')).size, 'bytes; names:', idx.map(i => i[3]).join(', '));
