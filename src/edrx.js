// Builds parts/data19.js, the ED pharmacy drug list, from sources/pharmacy/list.json (the list as printed, checked line by
// line against its four page images) and sources/pharmacy/formulary.json (each drug's prescriber category in the MOH
// Medicines Formulary, matched by generic name and strength from MyFormulary's public data, with an e-service search link).
// Run: node edrx.js
const fs = require('fs'), path = require('path');
const SRC = path.join(__dirname, '..', 'sources', 'pharmacy');
const L = JSON.parse(fs.readFileSync(path.join(SRC, 'list.json'), 'utf8'));
const F = Object.fromEntries(JSON.parse(fs.readFileSync(path.join(SRC, 'formulary.json'), 'utf8')).map(r => [r.no, r]));
/* As printed, with two readings settled: row 72's decimal mark is unclear on the scan (read as 0.1%), and row 144's
   double space is a single one. */
const FIX = {72: 'Gamma Benzene Hexachloride 0.1% Lotion'};
const tidy = s => s.replace(/\s+/g, ' ').trim();
const items = L.map(r => {
  const f = F[r.no] || {};
  let note = (f.note || '').replace(/ ?\(v\d+\.\d+\)/g, '').replace(/MyFormulary's public data/g, 'the formulary\'s public list');
  if (r.no === 72) note = 'The scan\'s decimal mark is unclear (0.1% or 0,1%). ' + note;
  return [r.no, tidy(FIX[r.no] || r.name), f.category || '', f.category ? f.url : '', tidy(note)];
});
if (items.length !== 155) throw new Error('expected 155 drugs, got ' + items.length);
const out = `/* ================= GENERATED by src/edrx.js from sources/pharmacy/: do not edit by hand =================
   The ED pharmacy drug list: "Senarai Ubat Farmasi Kecemasan HKL", Jabatan Farmasi, HKL, updated ("Tarikh kemaskini")
   14 Apr 2025, which Krishna gave on 12 Nov 2026: 155 drugs as printed, in its order. A department document (standing
   rule 6), labelled with its source and date; the names of the pharmacists who prepared and verified it are not copied.
   Each drug's prescriber category is from the MOH Medicines Formulary (FUKKM), matched by generic name and strength in
   MyFormulary's public data (version 261014.0003, 5 Nov 2026); the link is the formulary's own e-service search. No
   indication or dose is copied from the formulary (its portal reserves all rights). [no, name, category, link, note] */
const EDRX = {
  src:'Senarai Ubat Farmasi Kecemasan HKL, Jabatan Farmasi HKL, updated 14 Apr 2025',
  fx:'MOH Medicines Formulary (FUKKM), MyFormulary data of 5 Nov 2026',
  items:${JSON.stringify(items).replace(/\],\[/g, '],\n    [')}
};
`;
fs.writeFileSync(path.join(__dirname, 'parts', 'data19.js'), out);
const n = items.filter(i => i[2]).length;
console.log('data19.js: ' + items.length + ' drugs, ' + n + ' with a formulary category');
